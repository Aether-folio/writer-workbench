import test from 'node:test';
import assert from 'node:assert/strict';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StdioClientTransport} from '@modelcontextprotocol/sdk/client/stdio.js';
import {fileURLToPath} from 'node:url';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join,resolve,sep} from 'node:path';

test('正式MCP协议可列出两个入口、读取自含界面且不访问正文', async()=>{
  const serverPath=process.env.WORKBENCH_TEST_SERVER || fileURLToPath(new URL('../dist/server.mjs',import.meta.url));
  const directory=await mkdtemp(join(tmpdir(),'writer-mcp-test-'));
  const notesPath=join(directory,'annotations.json');
  const transport=new StdioClientTransport({command:process.execPath,args:[serverPath],stderr:'pipe',env:{...process.env,WORKBENCH_WORKSPACE:directory,WORKBENCH_ANNOTATIONS_PATH:notesPath}});
  const client=new Client({name:'writer-integration-test',version:'1.0.0'});
  try {
    await client.connect(transport);
    const tools=await client.listTools();
    const open=tools.tools.find(tool=>tool.name==='open_workbench');
    assert.ok(open);
    assert.deepEqual(open._meta['openai/ui'].entrypoints,[{type:'global'},{type:'thread'}]);
    const resources=await client.listResources();
    assert.equal(resources.resources.length,1);
    const resource=await client.readResource({uri:open._meta.ui.resourceUri});
    assert.equal(resource.contents[0].mimeType,'text/html;profile=mcp-app');
    assert.ok(resource.contents[0].text.includes('draft-body'));
    assert.ok(resource.contents[0].text.includes('stats-pet-enabled'));
    assert.equal((resource.contents[0].text.match(/data:image\/gif;base64,/g) || []).length,4);
    assert.deepEqual(resource.contents[0]._meta['openai/ui'].availableDisplayModes,['fullscreen','inline']);
    const result=await client.callTool({name:'open_workbench',arguments:{}});
    assert.equal(result.isError,undefined);
    assert.equal(result.structuredContent.manuscriptAccess,'workbench-folder-only');
    assert.equal(result.structuredContent.draftOnly,false);
    assert.deepEqual(result.structuredContent.chatMessage,{target:'active',send:true});
    assert.equal(tools.tools.some(tool=>['save_annotation','list_annotations'].includes(tool.name)),false);
    const publish=tools.tools.find(tool=>tool.name==='publish_writing_suggestion');
    assert.ok(publish);assert.equal(publish._meta?.ui?.visibility,undefined);
    assert.deepEqual(tools.tools.find(tool=>tool.name==='update_writing_request')._meta.ui.visibility,['app']);
    const createdRequest=await client.callTool({name:'create_writing_request',arguments:{path:'',title:'协议草稿',body:'',offset:0,instruction:'写一句'}});
    const request=createdRequest.structuredContent.request;
    const context=await client.callTool({name:'get_writing_request',arguments:{path:'',instruction:'写一句'}});
    assert.equal(context.isError,undefined);
    assert.equal(JSON.parse(context.content[0].text).requestId,request.id);
    assert.equal(tools.tools.find(tool=>tool.name==='get_writing_request').annotations.readOnlyHint,true);
    const response=await client.callTool({name:'publish_writing_suggestion',arguments:{requestId:request.id,generation:request.generation,text:'协议回传建议'}});
    assert.equal(response.isError,undefined);
    const pending=await client.callTool({name:'writing_requests',arguments:{path:''}});
    assert.equal(pending.structuredContent.requests[0].text,'协议回传建议');
    const info=await client.callTool({name:'workspace_info',arguments:{}});
    assert.equal(info.structuredContent.folder,'码字工作台');
    const createdWork=await client.callTool({name:'create_work',arguments:{name:'协议测试作品'}});
    assert.equal(createdWork.structuredContent.work.name,'协议测试作品');
    const withWork=await client.callTool({name:'workspace_info',arguments:{}});
    assert.equal(withWork.structuredContent.works[0].name,'协议测试作品');
    assert.ok(withWork.structuredContent.directories.some(folder=>folder.path==='协议测试作品/正文'));
    const preferences=await client.callTool({name:'save_stats_preferences',arguments:{fields:['work','words'],workPath:'协议测试作品',pet:{enabled:true,character:'fish'}}});
    assert.deepEqual(preferences.structuredContent.fields,['work','words']);
    assert.equal(preferences.structuredContent.coverDataUrl,null);
    assert.deepEqual(preferences.structuredContent.pet,{enabled:true,character:'fish'});
    const preferencesRead=await client.callTool({name:'stats_preferences',arguments:{workPath:'协议测试作品'}});
    assert.deepEqual(preferencesRead.structuredContent.fields,['work','words']);
    assert.deepEqual(preferencesRead.structuredContent.pet,{enabled:true,character:'fish'});
    const document=await client.callTool({name:'save_document',arguments:{path:'文稿/协议测试.md',body:'用户写的正文'}});
    assert.ok(!document.isError);
    const opened=await client.callTool({name:'read_document',arguments:{path:document.structuredContent.path}});
    assert.equal(opened.structuredContent.body,'用户写的正文');
    const stage=tools.tools.find(tool=>tool.name==='stage_chat_edits');
    assert.ok(stage);
    assert.equal(stage._meta?.ui?.visibility,undefined);
    const named=await client.callTool({name:'save_document',arguments:{path:'文稿/聊天改稿.md',body:'开头。\r\n重复。\r\n重复。\r\n结尾。'}});
    const target=named.structuredContent;
    const edits=[{original:'开头。',replacement:'改写开头。'},{original:'结尾。',replacement:'改写结尾。'}];
    const stageEdits=edits=>client.callTool({name:stage.name,arguments:{path:target.path,instruction:'分开改两处',edits}});
    const ambiguous=await stageEdits([edits[0],{original:'重复。',replacement:'别猜。'}]);
    assert.equal(ambiguous.isError,true);
    const listSuggestions=async()=> (await client.callTool({name:'writing_requests',arguments:{path:target.path}})).structuredContent.requests;
    assert.equal((await listSuggestions()).length,0);
    const staged=await stageEdits(edits);
    assert.equal(staged.isError,undefined);
    const proposals=JSON.parse(staged.content[0].text).suggestions;
    assert.equal(proposals.length,2);
    const retried=await stageEdits(edits);
    assert.deepEqual(JSON.parse(retried.content[0].text).suggestions,proposals);
    const listed=await listSuggestions();
    assert.equal(listed.length,proposals.length);
    const byId=new Map(listed.map(request=>[request.id,request]));
    const [first,second]=proposals.map(({id})=>byId.get(id));
    for(const [index,request] of [first,second].entries()){
      assert.ok(request);
      assert.equal(request.status,'ready');
      assert.equal(request.origin,'chat');
      assert.equal(request.text,edits[index].replacement);
      assert.equal(request.baseBody.slice(request.offset,request.endOffset),edits[index].original);
    }
    const unchanged=await client.callTool({name:'read_document',arguments:{path:target.path}});
    assert.equal(unchanged.structuredContent.body,target.body);
    const accepted=await client.callTool({name:'update_writing_request',arguments:{id:first.id,version:first.version,action:'accept',body:target.body.replace(/\r\n/g,'\n'),revision:target.revision}});
    assert.equal(accepted.structuredContent.document.body,'改写开头。\r\n重复。\r\n重复。\r\n结尾。');
    await client.callTool({name:'update_writing_request',arguments:{id:second.id,version:second.version,action:'discard'}});
    assert.equal((await listSuggestions()).length,0);
    const remove=tools.tools.find(tool=>tool.name==='delete_document');
    assert.deepEqual(remove._meta.ui.visibility,['app']);assert.equal(remove.annotations.destructiveHint,true);
    const deleted=await client.callTool({name:'delete_document',arguments:{path:document.structuredContent.path,revision:document.structuredContent.revision}});
    assert.equal(deleted.structuredContent.deleted,true);
    const trash=await client.callTool({name:'list_trash',arguments:{}});
    assert.equal(trash.structuredContent.entries.length,1);
    const restored=await client.callTool({name:'restore_document',arguments:{id:deleted.structuredContent.entry.id}});
    assert.equal(restored.structuredContent.path,document.structuredContent.path);
    const recovered=await client.callTool({name:'read_document',arguments:{path:document.structuredContent.path}});
    assert.equal(recovered.structuredContent.body,'用户写的正文');
    const purge=tools.tools.find(tool=>tool.name==='delete_trash');
    assert.equal(purge.annotations.destructiveHint,true);
    const redel=await client.callTool({name:'delete_document',arguments:{path:recovered.structuredContent.path,revision:recovered.structuredContent.revision}});
    const purged=await client.callTool({name:'delete_trash',arguments:{id:redel.structuredContent.entry.id}});
    assert.equal(purged.structuredContent.deleted,true);
    const empty=await client.callTool({name:'list_trash',arguments:{}});assert.equal(empty.structuredContent.entries.length,0);
    const invalid=await client.callTool({name:'save_document',arguments:{path:'../正文.md',body:'拒绝'}});
    assert.equal(invalid.isError,true);
  } finally {
    await client.close();
    assert.ok(resolve(directory).startsWith(resolve(tmpdir())+sep));assert.ok(directory.includes('writer-mcp-test-'));
    await rm(directory,{recursive:true,force:true});
  }
});
