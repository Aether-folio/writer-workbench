const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const {fixture}=require('./browser.cjs');
const assert=require('node:assert/strict');
const {resolve}=require('node:path');
(async()=>{
 const browser=await chromium.launch({...(process.env.PLAYWRIGHT_CHANNEL ? {channel:process.env.PLAYWRIGHT_CHANNEL} : {}),headless:true});
 try {
  const {page,frame,errors}=await fixture(browser,true);
  await frame.locator('.file-entry').click();
  await frame.locator('#document-status').filter({hasText:'已打开'}).waitFor();
  const body=await frame.locator('#draft-body').evaluate(el=>el.value);
  const float=await frame.locator('#stats-float').boundingBox();
  await frame.locator('#writing-fullscreen').click();
  assert.equal(await frame.locator('#workbench-sidebar').isVisible(),false);
  assert.equal(await frame.locator('.desk-header').isVisible(),false);
  assert.equal(await frame.locator('.document-footer').isVisible(),false);
  assert.equal(await frame.locator('#stats-float').isVisible(),true);
  assert.deepEqual(await frame.locator('#stats-float').boundingBox(),float);
  assert.equal(await frame.locator('#writing-fullscreen-exit').isVisible(),true);
  assert.ok(await frame.locator('.document').evaluate(el=>{const box=el.getBoundingClientRect();return box.x===0 && box.y===0 && Math.abs(box.width-innerWidth)<1 && Math.abs(box.height-innerHeight)<1;}));
  await page.screenshot({path:resolve(__dirname,'../test-results/writing-fullscreen.png')});
  await frame.locator('#writing-fullscreen-exit').click();assert.equal(await frame.locator('#workbench-sidebar').isVisible(),true);
  await frame.locator('#writing-fullscreen').click();await frame.locator('#writing-fullscreen-exit').press('Escape');
  assert.equal(await frame.locator('#workbench-sidebar').isVisible(),true);
  assert.equal(await frame.locator('#draft-body').evaluate(el=>el.value),body);
  await page.evaluate(()=>document.getElementById('app').contentWindow.postMessage({method:'workbench/fullscreen',params:{active:true}},'*'));
  await frame.locator('body.writing-fullscreen').waitFor({state:'attached'});
  await page.evaluate(()=>document.getElementById('app').contentWindow.postMessage({method:'workbench/fullscreen',params:{active:false}},'*'));
  await frame.locator('body:not(.writing-fullscreen)').waitFor();
  assert.equal(await frame.locator('#files-status').isVisible(),false);
  assert.ok(await frame.locator('#stats-work').evaluate(el=>parseFloat(getComputedStyle(el).fontSize)>=16 && Number(getComputedStyle(el).fontWeight)>=700));
  assert.ok((await frame.locator('#trash-open').textContent()).includes('回收站'));
  await frame.getByRole('button',{name:'删除 已有章节.md',exact:true}).click();await frame.locator('#delete-confirm').click();
  await frame.locator('#delete-dialog').waitFor({state:'hidden'});
  assert.equal(await frame.locator('#feedback').textContent(),'');
  await frame.locator('#trash-open').click();await frame.locator('.trash-item').waitFor();
  assert.equal(await frame.locator('.trash-item button').count(),2);
  await frame.locator('.trash-remove').click();await frame.locator('#trash-delete-cancel').click();
  assert.equal(await frame.locator('.trash-item').count(),1);
  await page.evaluate(()=>{window.testPurgeError=true;});
  await frame.locator('.trash-remove').click();await frame.locator('#trash-delete-confirm').click();
  await frame.locator('#trash-delete-error').filter({hasText:'测试删除失败'}).waitFor();
  assert.equal(await page.evaluate(()=>window.testTrash.length),1);
  assert.equal(await frame.locator('#trash-delete-confirm').isEnabled(),true);
  await page.screenshot({path:resolve(__dirname,'../test-results/trash-delete-confirmation.png')});
  await page.evaluate(()=>{window.testPurgeError=false;});await frame.locator('#trash-delete-confirm').click();
  await frame.locator('#trash-status').filter({hasText:'回收站为空'}).waitFor();
  assert.equal(await page.evaluate(()=>window.testTrash.length),0);
  await frame.locator('#trash-close').click();
  await page.setViewportSize({width:360,height:800});await frame.locator('#writing-fullscreen').click();
  assert.equal(await frame.locator('#writing-fullscreen-exit').isVisible(),true);
  assert.ok(await frame.locator('.document-header').evaluate(el=>el.scrollWidth<=el.clientWidth));
  assert.deepEqual(errors,[]);await page.close();
  console.log('PASS: fullscreen and both exit paths; native host transition; float unchanged; narrow screen; larger work title; clean hints; trash confirmation/cancel/failure retention/retry/purge');
 } finally {await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
